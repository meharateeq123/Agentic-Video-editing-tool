// timeline.ts is generated from transcript.json rather than typed by hand: the cut points are
// the voiceover's own pause-aligned boundaries, and a single mistyped decimal puts every scene
// after it out of sync with the narration.
import {readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';

const project = resolve('D:\\flick\\output\\nemechek1');
const t = JSON.parse(await readFile(resolve(project, 'transcript.json'), 'utf8'));

const cuts = t.segments
  .map((s, i) => `  {n: ${i + 1}, start: ${s.start}, end: ${s.end}},`)
  .join('\n');

// Transition into each scene, cycled so the same move never lands twice in a row and each one
// matches the beat of the line it opens.
const KINDS = ['push', 'wipe', 'whip', 'dip', 'push', 'whipDown', 'wipe', 'whip', 'push', 'dip'];
const transitions = t.segments
  .map((s, i) => {
    if (i === 0) return '  null, // 1  film opens';
    const kind = KINDS[(i - 1) % KINDS.length];
    return `  '${kind}', // ${i + 1}  ${s.text.slice(0, 46).replace(/'/g, "\\'")}`;
  })
  .join('\n');

const out = `// Scene timing comes straight from transcript.json (voiceover pause-aligned).
// Generated by gen-timeline.mjs — these are the timeline, nothing here is estimated.

export const FPS = 30;
export const FILM_SECONDS = ${t.duration};

export type Cut = {n: number; start: number; end: number};

export const CUTS: Cut[] = [
${cuts}
];

export const startFrame = (n: number) => Math.round(CUTS[n - 1].start * FPS);
export const endFrame = (n: number) => Math.round(CUTS[n - 1].end * FPS);
export const sceneFrames = (n: number) => endFrame(n) - startFrame(n);
export const TOTAL_FRAMES = Math.round(FILM_SECONDS * FPS);

/**
 * Overlap window used by every transition. Each scene bleeds this many frames past its own cut
 * so the incoming scene has something to transition over.
 */
export const OVERLAP = 16;

/** Beats inside a scene run this much past the scene end to cover the bleed. */
export const BLEED = 20;

export type TKind = 'dip' | 'whip' | 'push' | 'wipe' | 'whipDown';

/** Transition INTO each scene. Index 0 is scene 1 (film open — no transition). */
export const TRANSITION_IN: (TKind | null)[] = [
${transitions}
];
`;

await writeFile(resolve(project, 'remotion', 'src', 'timeline.ts'), out);
console.log(`timeline.ts written — ${t.segments.length} scenes, ${t.duration}s, ${Math.round(t.duration * 30)} frames`);
for (const [i, s] of t.segments.entries()) {
  console.log(`  s${i + 1}: ${s.start}-${s.end} (${(s.end - s.start).toFixed(2)}s)`);
}
