// Builds src/timeline.ts from the script.
//
// Two modes:
//   node gen-timeline.mjs            — provisional. Splits the film by word count at a typical
//                                      narration rate, so scenes can be built and previewed before
//                                      the voiceover exists.
//   node gen-timeline.mjs vo.wav     — final. Re-cuts the same scenes against the real recording,
//                                      snapping every boundary to a silence in it, so the picture
//                                      lands on the narration rather than near it.
//
// Everything downstream reads timeline.ts, so switching from provisional to VO-aligned is one
// command and no scene edits.
import {readFileSync, writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const FPS = 30;
const WORDS_PER_SEC = 2.5; // ~150 wpm, a normal documentary read
const OVERLAP = 16;
const BLEED = 20;

const paragraphs = readFileSync('source-script.txt', 'utf8')
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter(Boolean);

const words = paragraphs.map((p) => p.split(/\s+/).length);
const total = words.reduce((a, b) => a + b, 0);

const voPath = process.argv[2];
let filmSeconds;
let silences = [];

if (voPath) {
  // remotion/node_modules isn't installed yet in fresh projects; fall back to a sibling project's
  // copy of the same pinned ffmpeg-static rather than gating alignment on a full npm install.
  let ffmpeg;
  try {
    ffmpeg = require('./remotion/node_modules/ffmpeg-static');
  } catch {
    ffmpeg = require('../cleetus2/remotion/node_modules/ffmpeg-static');
  }
  // ffmpeg always logs duration/silencedetect to stderr, and exits non-zero on the bare probe (no
  // output file) but zero on the -f null run — so stderr has to be read off spawnSync's result
  // directly rather than execFileSync, which only surfaces stdout on a successful exit.
  const run = (args) => spawnSync(ffmpeg, args, {encoding: 'utf8'}).stderr || '';

  const probe = run(['-i', voPath, '-hide_banner']);
  const m = /Duration: (\d+):(\d+):([\d.]+)/.exec(probe);
  filmSeconds = +m[1] * 3600 + +m[2] * 60 + +m[3];

  // Then every pause in it, as candidate cut points.
  const det = run(['-i', voPath, '-af', 'silencedetect=noise=-40dB:d=0.15', '-f', 'null', '-']);
  silences = [...det.matchAll(/silence_start: ([\d.]+)/g)].map((s) => +s[1]);
  console.log(`VO ${filmSeconds.toFixed(2)}s, ${silences.length} silences detected`);
} else {
  filmSeconds = total / WORDS_PER_SEC;
  console.log(`No VO given — provisional timeline, ${filmSeconds.toFixed(2)}s from word count`);
}

// Proportional targets, then (with a VO) snapped to the nearest real pause.
const cuts = [];
let acc = 0;
let cursor = 0;
for (let i = 0; i < paragraphs.length; i++) {
  const start = cursor;
  acc += words[i];
  let end = (acc / total) * filmSeconds;
  if (i === paragraphs.length - 1) {
    end = filmSeconds;
  } else if (silences.length) {
    let best = end;
    let bestD = Infinity;
    for (const s of silences) {
      const d = Math.abs(s - end);
      if (d < bestD && d < 3.5 && s > start + 1.5) {
        best = s;
        bestD = d;
      }
    }
    end = best;
  }
  cuts.push({n: i + 1, start: +start.toFixed(2), end: +end.toFixed(2)});
  cursor = end;
}

// Transition into each scene. Cycled rather than random so the film never plays the same move
// twice in a row, and never lands on a pattern the viewer can predict either. Scene 1 has nothing
// to transition from.
const KINDS = ['dip', 'push', 'whip', 'wipe', 'whipDown'];
const transitions = cuts.map((_, i) => (i === 0 ? 'dip' : KINDS[(i * 2 + 1) % KINDS.length]));

const src = `// Scene timing. ${
  voPath ? 'Pause-aligned to the voiceover.' : 'PROVISIONAL — word-count estimate, no voiceover yet.'
}
// Generated by gen-timeline.mjs; nothing here is hand-edited.

export const FPS = ${FPS};
export const FILM_SECONDS = ${filmSeconds.toFixed(2)};
export const OVERLAP = ${OVERLAP};
export const BLEED = ${BLEED};

// No cold-open hook clip in this film - the VO starts at frame 0. HOOK_SECONDS stays 0 so every
// downstream offset (FinalFilm.tsx, TOTAL_FRAMES) is a no-op rather than a special case.
export const HOOK_SECONDS = 0;
export const HOOK_FRAMES = Math.round(HOOK_SECONDS * FPS);
export const VO_ALIGNED = ${Boolean(voPath)};

export type Cut = {n: number; start: number; end: number};
export type TKind = 'dip' | 'whip' | 'whipDown' | 'push' | 'wipe';

export const TRANSITION_IN: TKind[] = [
${transitions.map((t, i) => `  '${t}', // ${i + 1}  ${paragraphs[i].slice(0, 64).replace(/\s+/g, ' ')}`).join('\n')}
];

export const CUTS: Cut[] = [
${cuts.map((c) => `  {n: ${c.n}, start: ${c.start}, end: ${c.end}},`).join('\n')}
];

export const startFrame = (n: number) => Math.round(CUTS[n - 1].start * FPS);
export const endFrame = (n: number) => Math.round(CUTS[n - 1].end * FPS);
export const sceneFrames = (n: number) => endFrame(n) - startFrame(n);

/**
 * How many frames a scene is actually mounted for. Every scene but the last carries OVERLAP extra
 * frames so the next one can cross over it, and a scene's footage has to cover those frames too.
 */
export const mountedFrames = (n: number) =>
  sceneFrames(n) + (n === CUTS.length ? 0 : OVERLAP);

export const TOTAL_FRAMES = Math.round(FILM_SECONDS * FPS) + HOOK_FRAMES;
`;

writeFileSync('remotion/src/timeline.ts', src);
console.log(`Wrote timeline.ts — ${cuts.length} scenes, ${filmSeconds.toFixed(2)}s`);
for (const c of cuts) {
  console.log(`  ${String(c.n).padStart(2)}  ${c.start.toFixed(2)} -> ${c.end.toFixed(2)}  (${(c.end - c.start).toFixed(1)}s)`);
}
