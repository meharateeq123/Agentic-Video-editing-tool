// Generates remotion/src/footage.ts for long5 from plan.mjs and copies each used source into
// remotion/public/bed-pool (faststart, stream copy). Validates: beats per scene, every beat <= 3s (90f),
// no source range used twice inside this film, and none of it collides with what long3 / long4 / the shorts used.
import {readFileSync, writeFileSync, existsSync, mkdirSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {PLAN, SRC, EXCL} from './plan.mjs';

const FPS = 30;
const OVERLAP = 16;
const CUTS = JSON.parse(readFileSync('cuts.json', 'utf8'));
const mounted = (n) => Math.round(CUTS[n - 1].end * FPS) - Math.round(CUTS[n - 1].start * FPS) + (n === CUTS.length ? 0 : OVERLAP);
const FF = 'D:/flick/output/long2/remotion/node_modules/ffmpeg-static/ffmpeg.exe';
const POOL = 'remotion/public/bed-pool';
mkdirSync(POOL, {recursive: true});

let bad = 0;
const used = {}; // key -> [[a, b, scene]]
const chains = {};
for (let n = 1; n <= CUTS.length; n++) {
  const T = mounted(n);
  const need = Math.ceil(T / 90);
  const list = PLAN[n] || [];
  if (list.length !== need) {
    console.log(`scene ${n}: ${list.length} beats, needs ${need} (${T}f)`);
    bad++;
    continue;
  }
  const base = Math.floor(T / need);
  let extra = T - base * need;
  chains[n] = list.map((b) => {
    const [key, t] = b.split('@');
    const frames = base + (extra-- > 0 ? 1 : 0);
    const start = Number(t);
    if (!SRC[key]) throw new Error(`unknown source ${key}`);
    const end = start + frames / FPS;
    for (const [a, z, sc] of used[key] ?? []) if (start < z && end > a) { console.log(`OVERLAP ${b} (scene ${n}) with ${key}@${a}-${z.toFixed(1)} (scene ${sc})`); bad++; }
    for (const [a, z] of EXCL[SRC[key].grp] ?? []) if (start < z + 0.5 && end > a - 0.5) { console.log(`ALREADY USED ${b} (scene ${n}) collides with ${a}-${z} elsewhere`); bad++; }
    (used[key] ??= []).push([start, end, n]);
    return {key, start, frames};
  });
}

// copy sources (faststart)
const keys = [...new Set(Object.values(chains).flat().map((l) => l.key))];
for (const k of keys) {
  const out = `${POOL}/${k.toLowerCase()}.mp4`;
  if (existsSync(out)) continue;
  console.log('copying', k);
  const r = spawnSync(FF, ['-hide_banner', '-loglevel', 'error', '-y', '-i', SRC[k].file, '-c', 'copy', '-movflags', '+faststart', out]);
  if (r.status !== 0) { console.log('copy failed', k); bad++; }
}

const header = `/**
 * Scene -> chain of bed clips. Generated by build-footage.mjs from plan.mjs (regenerate if scene durations change).
 * Every link holds the screen <= 3s and no range of any source appears twice - not in this film, not in
 * long3/long4 (same Bristol race), not in the kansas1/kansas2/chase2 shorts.
 *
 * Sources (720p h264):
${Object.entries(SRC).map(([k, s]) => ` *   ${k.padEnd(4)} ${s.note} (${s.grp})`).join('\n')}
 */`;

const out = `${header}

export type Bed = {
  src: string;
  startFrom: number;
  span: number;
  zoom?: number;
  offX?: number;
  offY?: number;
  driftX?: number;
  driftY?: number;
  exposure?: number;
  saturate?: number;
};

export type Link = Bed & {frames: number};

const P_ = (name: string) => \`bed-pool/\${name}.mp4\`;

const L = (
  file: string,
  startFrom: number,
  frames: number,
  extra: Omit<Bed, 'src' | 'startFrom' | 'span'> = {},
): Link => ({src: P_(file), startFrom, frames, span: (frames + 22) / 30, ...extra});

${keys.map((k) => `const ${k} = '${k.toLowerCase()}';`).join('\n')}

export const CHAINS: Record<number, Link[]> = {
${Object.entries(chains).map(([n, ls]) => `  ${n}: [\n${ls.map((l) => `    L(${l.key}, ${l.start}, ${l.frames}),`).join('\n')}\n  ],`).join('\n')}
};

export const chain = (n: number): Link[] => CHAINS[n];
`;
if (bad === 0) {
  writeFileSync('remotion/src/footage.ts', out);
  console.log('wrote footage.ts', Object.values(chains).flat().length, 'links');
} else console.log('NOT written, problems:', bad);
