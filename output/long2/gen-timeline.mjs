// Builds remotion/src/timeline.ts by aligning every script paragraph to the Whisper word timestamps
// (LCS alignment over normalised words), not by snapping proportional guesses to silences. Each scene
// boundary sits at the midpoint of the gap before the paragraph's first spoken word.
// Also writes vo/words.json (flat word list) for when.mjs beat lookups.
import {readFileSync, writeFileSync} from 'node:fs';

const FPS = 30;
const OVERLAP = 16;
const HOOK_SECONDS = 10;

const norm = (w) => w.toLowerCase().replace(/[^a-z0-9]/g, '');
const paragraphs = readFileSync('source-script.txt', 'utf8').split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
const script = [];
paragraphs.forEach((p, pi) => p.split(/\s+/).forEach((w) => norm(w) && script.push({w: norm(w), pi})));

const wj = JSON.parse(readFileSync('vo/long2.json', 'utf8'));
const words = wj.segments.flatMap((s) => s.words).map((w) => ({w: norm(w.word), raw: w.word.trim(), start: w.start, end: w.end})).filter((w) => w.w);
writeFileSync('vo/words.json', JSON.stringify(words));

const filmSeconds = Number(process.argv[2]);
if (!filmSeconds) throw new Error('pass the VO duration in seconds');

// LCS alignment
const n = script.length, m = words.length;
const dp = Array.from({length: n + 1}, () => new Int32Array(m + 1));
for (let i = n - 1; i >= 0; i--)
  for (let j = m - 1; j >= 0; j--)
    dp[i][j] = script[i].w === words[j].w ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
const map = new Array(n).fill(-1);
for (let i = 0, j = 0; i < n && j < m; ) {
  if (script[i].w === words[j].w) { map[i] = j; i++; j++; }
  else if (dp[i + 1][j] >= dp[i][j + 1]) i++;
  else j++;
}
console.log(`aligned ${map.filter((x) => x >= 0).length}/${n} script words to ${m} spoken words`);

// first aligned transcript word of each paragraph
const firstIdx = paragraphs.map((_, pi) => {
  const idxs = script.map((s, i) => (s.pi === pi && map[i] >= 0 ? map[i] : -1)).filter((x) => x >= 0);
  return idxs.length ? Math.min(...idxs) : -1;
});

const starts = firstIdx.map((j, pi) => {
  if (pi === 0) return 0;
  if (j < 0) throw new Error(`paragraph ${pi + 1} could not be aligned`);
  const prevEnd = words[j - 1] ? words[j - 1].end : 0;
  return (prevEnd + words[j].start) / 2;
});
const cuts = paragraphs.map((_, i) => ({n: i + 1, start: +starts[i].toFixed(2), end: +(i === paragraphs.length - 1 ? filmSeconds : starts[i + 1]).toFixed(2)}));

const KINDS = ['dip', 'push', 'whip', 'wipe', 'whipDown'];
const transitions = cuts.map((_, i) => (i === 0 ? 'dip' : KINDS[(i * 2 + 1) % KINDS.length]));

const src = `// Scene timing, aligned word-by-word to the Whisper transcript of vo/long2.wav.
// Generated by gen-timeline.mjs; nothing here is hand-edited.

export const FPS = ${FPS};
export const FILM_SECONDS = ${filmSeconds.toFixed(2)};
export const OVERLAP = ${OVERLAP};
export const BLEED = 20;

// Suspense-montage cold open (flick-suspense-hook-format): a fixed 15s real-audio hook plays before
// the VO. Every scene's \`from\` is pushed forward by HOOK_FRAMES in FinalFilm.tsx.
export const HOOK_SECONDS = ${HOOK_SECONDS};
export const HOOK_FRAMES = Math.round(HOOK_SECONDS * FPS);
export const VO_ALIGNED = true;

export type Cut = {n: number; start: number; end: number};
export type TKind = 'dip' | 'whip' | 'whipDown' | 'push' | 'wipe';

export const TRANSITION_IN: TKind[] = [
${transitions.map((t, i) => `  '${t}', // ${i + 1}  ${paragraphs[i].slice(0, 64).replace(/\s+/g, ' ')}`).join('\n')}
];

export const CUTS: Cut[] = [
${cuts.map((c) => `  {n: ${c.n}, start: ${c.start}, end: ${c.end}},`).join('\n')}
];

export const startFrame = (n: number) => Math.round(CUTS[n - 1].start * FPS);
export const endFrame = (n: number) => Math.round(CUTS[n - 1].end * FPS);
export const sceneFrames = (n: number) => endFrame(n) - startFrame(n);

/** Frames a scene is mounted for: every scene but the last carries OVERLAP extra for the crossover. */
export const mountedFrames = (n: number) => sceneFrames(n) + (n === CUTS.length ? 0 : OVERLAP);

export const TOTAL_FRAMES = Math.round(FILM_SECONDS * FPS) + HOOK_FRAMES;
`;
writeFileSync('remotion/src/timeline.ts', src);
writeFileSync('cuts.json', JSON.stringify(cuts));
for (const c of cuts) console.log(`  ${String(c.n).padStart(2)}  ${c.start.toFixed(2)} -> ${c.end.toFixed(2)}  (${(c.end - c.start).toFixed(1)}s)  ${paragraphs[c.n - 1].slice(0, 50)}`);


